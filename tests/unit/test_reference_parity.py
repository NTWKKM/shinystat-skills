# ---------------------------------------------------------------------------
# IPTW binary outcome: robust SE must be the probability-weight sandwich
# ---------------------------------------------------------------------------
def _pw_sandwich_se(y, t, w, hc1=False):
    # statsmodels GLM applies no n/(n-p) factor for cov_type="HC1", so the engine equals HC0.
    import statsmodels.api as sm

    X = sm.add_constant(np.asarray(t, dtype=float))
    b = sm.GLM(y, X, family=sm.families.Binomial(), var_weights=w).fit().params
    mu = 1.0 / (1.0 + np.exp(-X @ b))
    bread = np.linalg.inv((X * (w * mu * (1 - mu))[:, None]).T @ X)
    score = X * (w * (y - mu))[:, None]
    V = bread @ score.T @ score @ bread
    n, p = X.shape
    return float(np.sqrt(V[1, 1] * (n / (n - p) if hc1 else 1.0)))


def _iptw_frame(estimand):
    from medstat.causal.iptw import compute_iptw_weights

    rng = np.random.default_rng(1)
    n = 600
    x = rng.normal(size=n)
    t = rng.binomial(1, 1 / (1 + np.exp(-1.2 * x)))
    y = rng.binomial(1, 1 / (1 + np.exp(-(-0.5 + 0.5 * t + 0.7 * x))))
    df = pd.DataFrame({"t": t, "y": y, "x": x})
    return compute_iptw_weights(
        df, "t", ["x"], estimand=estimand, truncate_quantiles=None
    ).df


@pytest.mark.parametrize("estimand", ["ATE", "ATT", "ATO"])
def test_engine_iptw_binary_se_is_probability_weight_sandwich(estimand):
    from medstat.causal.iptw import fit_iptw_outcome_model

