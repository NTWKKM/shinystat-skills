def test_mediation_binary_mediator_and_outcome_recovers_natural_effects():
    from medstat.causal.mediation import run_mediation

    def ex(z):
        return 1 / (1 + np.exp(-z))

    g, b = (-0.5, 1.2, 0.4), (-1.0, 0.6, 1.1, 0.5)
    rng = np.random.default_rng(11)
    n = 40000
    x = rng.normal(size=n)
    t = rng.binomial(1, 0.5, n)
    m = rng.binomial(1, ex(g[0] + g[1] * t + g[2] * x))
    y = rng.binomial(1, ex(b[0] + b[1] * t + b[2] * m + b[3] * x))

    def ey(tt, tm):
        p = ex(g[0] + g[1] * tm + g[2] * x)
        return np.mean(
            p * ex(b[0] + b[1] * tt + b[2] + b[3] * x)
            + (1 - p) * ex(b[0] + b[1] * tt + b[3] * x)
        )

    truth_acme = 0.5 * ((ey(1, 1) - ey(1, 0)) + (ey(0, 1) - ey(0, 0)))
    truth_total = ey(1, 1) - ey(0, 0)
    r = run_mediation(
        pd.DataFrame({"t": t, "m": m, "y": y, "x": x}), "t", "m", "y", ["x"], n_sims=200
    )
    assert r["scale"] == "risk_difference"
    assert r["acme"] == pytest.approx(truth_acme, abs=0.006)  # ~3 sampling SE at n=40k
    assert r["total_effect"] == pytest.approx(truth_total, abs=0.01)
    assert r["acme"] + r["ade"] == pytest.approx(r["total_effect"], abs=1e-9)


