def _competing_risks_frame():
    rng = np.random.default_rng(7)
    n = 400
    x = rng.normal(size=n)
    g = rng.binomial(1, 0.5, n)
    t1 = rng.exponential(1 / np.exp(-1 + 0.5 * x + 0.4 * g))
    t2 = rng.exponential(1 / np.exp(-1.2 - 0.3 * x))
    c = rng.uniform(0, 4, n)
    t = np.minimum.reduce([t1, t2, c])
    e = np.select([t == t1, t == t2], [1, 2], 0)
    return pd.DataFrame({"time": np.round(t, 2) + 0.01, "status": e})


def test_cif_loglog_ci_matches_r_survfit():
    import re

    from medstat.models.survival import fit_competing_risks_cif

    d = _competing_risks_frame()
    res = fit_competing_risks_cif(d["time"], d["status"], horizons=[0.5, 1.0, 2.0])
    # R 4.x: summary(survfit(Surv(time, factor(status)) ~ 1, conf.type="log-log"), times=...)
    r_ref = [
        (0.2152469, 0.1753817, 0.2578834),
        (0.3306647, 0.2825332, 0.3794927),
        (0.4445004, 0.3892592, 0.4981949),
    ]
    for (_, row), ref in zip(res.horizon_summary.iterrows(), r_ref):
        got = [float(v) for v in re.findall(r"[0-9.]+", row["cif_primary_ci"])]
        # lifelines jitters tied times and the summary rounds to 3 dp
        np.testing.assert_allclose(got, ref, atol=2e-3)


