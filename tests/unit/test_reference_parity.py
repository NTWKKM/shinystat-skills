# Egger's regression test: asymmetry is the INTERCEPT of SND ~ precision
# ---------------------------------------------------------------------------
def _egger_reference_p(theta, se):
    import statsmodels.api as sm

    fit = sm.OLS(theta / se, sm.add_constant(1.0 / se)).fit()
    return float(fit.pvalues[0])


@pytest.mark.parametrize("intercept", [0.0, 3.0])
def test_recipe24_egger_tests_intercept_not_slope(recipes, intercept):
    rng = np.random.default_rng(2)
    k = 12
    se = rng.uniform(0.05, 0.4, k)
    # SND_i = intercept + theta * precision_i + N(0,1)  ->  theta_i = intercept*se + theta + e*se
    theta = 0.8 + intercept * se + rng.normal(0.0, se)
    df = pd.DataFrame(
        {"study": [f"S{i}" for i in range(k)], "log_effect": theta, "se": se}
    )
    res = recipes["run_meta_analysis"](df, exponentiate=False)
    egger_p = res["heterogeneity"]["egger_p_value"]
    assert egger_p == pytest.approx(_egger_reference_p(theta, se), rel=1e-6)


